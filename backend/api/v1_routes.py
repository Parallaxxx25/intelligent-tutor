@router.get(
    "/problems",
    response_model=list[ProblemV1],
    dependencies=[Depends(require_service_key)],
)
async def list_problems_v1(db: AsyncSession = Depends(get_db)) -> Any:
    """The catalog an integrator imports — map each id to your own problem
    rows (a `tutor_problem_id` column), don't re-key on title text.

    Scoped to problems imported from *this* integrator's own catalog
    (`external_problem_id IS NOT NULL`) — the 24 CSV-sourced problems that
    predate this integration stay in the table for existing eval artifacts
    but are never exposed here. See
    docs/adr/0006-partner-primary-dual-grade.md.
    """
    result = await db.execute(
        select(Problem)
        .where(Problem.external_problem_id.is_not(None))
        .order_by(Problem.id)
    )
    return [ProblemV1.model_validate(p) for p in result.scalars().all()]


