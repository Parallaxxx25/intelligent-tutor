logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v1", tags=["Grading + Hint Service"])

# Served when we graded a submission correct but the caller's own grader
# disagreed (see docs/adr/0006-partner-primary-dual-grade.md) — never
# generated by Gemini, since our own diagnosis has no error to explain.
_DISAGREEMENT_HINT_TEXT = (
    "Your query's results matched our reference answer, but the platform's "
    "own checker marked it incorrect. This is usually a column-name or "
    "row-order mismatch — double-check the exact column aliases and any "
    "ORDER BY the problem asks for."
)


